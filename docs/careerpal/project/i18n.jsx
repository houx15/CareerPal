window.I18N = I18N;
const LangContext = React.createContext({ lang: "zh", t: (k) => I18N.zh[k] || k, setLang: () => {} });
window.LangContext = LangContext;

const LangProvider = ({ children }) => {
  const [lang, setLang] = React.useState("zh"); // default Chinese
  const t = React.useCallback((k) => {
    const v = (I18N[lang] && I18N[lang][k]);
    return v !== undefined ? v : (I18N.en[k] || k);
  }, [lang]);
  React.useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  return React.createElement(LangContext.Provider, { value: { lang, t, setLang } }, children);
};
window.LangProvider = LangProvider;

const LangToggle = ({ compact = false }) => {
  const { lang, setLang } = React.useContext(LangContext);
  return (
    <div className={"lang-toggle" + (compact ? " compact" : "")}>
      <button className={lang === "en" ? "active" : ""} onClick={() => setLang("en")}>EN</button>
      <button className={lang === "zh" ? "active" : ""} onClick={() => setLang("zh")}>中文</button>
    </div>
  );
};
window.LangToggle = LangToggle;
